CREATE OR REPLACE VIEW "v_BaoCaoDoanhThuTheoToaNha" AS
SELECT 
    t."MaToaNha",
    t."TenToaNha",
    h."KyTinhTien",
    COUNT(h."MaHoaDon")::INT AS "TongSoHoaDon",
    SUM(h."TongTien") AS "TongTienPhatHanh",
    SUM(CASE WHEN h."TrangThai" = 'Đã thanh toán' THEN h."TongTien" ELSE 0 END) AS "DoanhThuDaThu",
    SUM(CASE WHEN h."TrangThai" <> 'Đã thanh toán' THEN h."TongTien" ELSE 0 END) AS "CongNoConLai",
    CAST(ROUND((SUM(CASE WHEN h."TrangThai" = 'Đã thanh toán' THEN h."TongTien" ELSE 0 END) * 100.0) / NULLIF(SUM(h."TongTien"), 0), 1) AS DECIMAL(5,1)) AS "TyLeThuHoi"
FROM "HoaDon" h
INNER JOIN "HopDong" hd ON h."MaHopDong" = hd."MaHopDong"
INNER JOIN "Phong" p ON hd."MaPhong" = p."MaPhong"
INNER JOIN "ToaNha" t ON p."MaToaNha" = t."MaToaNha"
GROUP BY t."MaToaNha", t."TenToaNha", h."KyTinhTien";

CREATE OR REPLACE VIEW "v_SoDoPhongRealTime" AS
SELECT 
    p."MaPhong",
    p."KyHieuPhong",
    p."SoTang",
    p."DienTich",
    p."SucChua",
    p."GiaThue",
    p."TrangThai" AS "TrangThaiPhong",
    t."MaToaNha",
    t."TenToaNha",
    lp."TenLoaiPhong",
    hd."MaHopDong",
    hd."SoHopDong",
    u."HoTen" AS "TenCuDanDaiDien",
    u."SoDienThoai" AS "SdtCuDan",
    COALESCE(debt."CongNoChuaThu", 0) AS "CongNoChuaThu",
    COALESCE(ticket."SoSuCoChuaXong", 0)::INT AS "SoSuCoChuaXong"
FROM "Phong" p
INNER JOIN "ToaNha" t ON p."MaToaNha" = t."MaToaNha"
INNER JOIN "LoaiPhong" lp ON p."MaLoaiPhong" = lp."MaLoaiPhong"
LEFT JOIN "HopDong" hd ON p."MaPhong" = hd."MaPhong" AND hd."TrangThai" = 'Đang hiệu lực'
LEFT JOIN "CuDanHopDong" cdhd ON hd."MaHopDong" = cdhd."MaHopDong" AND cdhd."LaDaiDien" = TRUE
LEFT JOIN "CuDan" c ON cdhd."MaCuDan" = c."MaCuDan"
LEFT JOIN "NguoiDung" u ON c."MaNguoiDung" = u."MaNguoiDung"
LEFT JOIN (
    SELECT hd_sub."MaPhong", SUM(h_sub."TongTien") AS "CongNoChuaThu"
    FROM "HoaDon" h_sub
    INNER JOIN "HopDong" hd_sub ON h_sub."MaHopDong" = hd_sub."MaHopDong"
    WHERE h_sub."TrangThai" <> 'Đã thanh toán'
    GROUP BY hd_sub."MaPhong"
) debt ON p."MaPhong" = debt."MaPhong"
LEFT JOIN (
    SELECT "MaPhong", COUNT("MaPhieuSuCo") AS "SoSuCoChuaXong"
    FROM "PhieuSuCo"
    WHERE "TrangThai" IN ('Chờ xử lý', 'Đang xử lý', 'Đang sửa')
    GROUP BY "MaPhong"
) ticket ON p."MaPhong" = ticket."MaPhong";

